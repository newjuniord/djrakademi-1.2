const months: Record<string, string> = {
  janvier: 'janvye', 'janv.': 'janv.', février: 'fevriye', 'févr.': 'fevr.',
  mars: 'mas', avril: 'avril', 'avr.': 'avr.', mai: 'me', juin: 'jen',
  juillet: 'jiyè', 'juil.': 'jiyè', août: 'out', septembre: 'septanm',
  'sept.': 'sept.', octobre: 'oktòb', 'oct.': 'okt.', novembre: 'novanm',
  'nov.': 'nov.', décembre: 'desanm', 'déc.': 'des.'
};

function translate(value: string): string {
  if (ht[value]) return ht[value];
  for (const [pattern, render] of patterns) {
    const match = value.match(pattern);
    if (match) return render(match);
  }
  if (/\d/.test(value)) {
    const localizedDate = value.replace(/\b(janvier|janv\.|février|févr\.|mars|avril|avr\.|mai|juin|juillet|juil\.|août|septembre|sept\.|octobre|oct\.|novembre|nov\.|décembre|déc\.)(?=\s|$)/gi, (month) => months[month.toLowerCase()] ?? month);
    if (localizedDate !== value) return localizedDate;
  }
  return value;
}

export function translateAdminMessage(value: string, language: Language): string {
  return language === 'ht' ? translate(value) : value;
}

export function translateAdminToastMessage(value: string, language: Language, type: 'success' | 'error' | 'info'): string {
  if (language !== 'ht') return value;
  const translated = translate(value);
  if (translated !== value || Object.values(ht).includes(value)) return translated;
  if (value.startsWith('Erreur : ')) {
    const detail = value.slice('Erreur : '.length);
    const translatedDetail = translate(detail);
    if (translatedDetail !== detail) return `Erè : ${translatedDetail}`;
  }
  if (type === 'error') return 'Yon erè rive. Tanpri eseye ankò.';
  if (type === 'info') return 'Enfòmasyon.';
  return 'Operasyon an fèt avèk siksè.';
}

